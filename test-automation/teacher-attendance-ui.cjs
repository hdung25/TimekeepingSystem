'use strict';
const assert = require('node:assert/strict');
module.exports = async ({env,admin,month,record,click,report,snapshot}) => {
    const id='audit-dual';
    const read=async()=>{let data;await env.withSecurityRulesDisabled(async c=>{data=(await c.firestore().collection('salary_settings_monthly').doc(`${month}_${id}`).get()).data();});return data;};
    const write=data=>env.withSecurityRulesDisabled(c=>c.firestore().collection('salary_settings_monthly').doc(`${month}_${id}`).set(data));
    let profile;
    await env.withSecurityRulesDisabled(async c=>{profile=(await c.firestore().collection('users').doc(id).get()).data();await c.firestore().collection('users').doc(id).update({teachingMode:'new'});});
    const original=await read();
    const attendance=data=>data.giao_vien.evaluation.find(r=>Number(r.id)===0).amount;
    const open=async()=>{await report(admin,id);await admin.select('#salary-role-filter','giao-vien');await admin.waitForFunction(()=>window.payrollReadyScope===window.currentReportScope&&window.currentLoadedRoleKey==='giao_vien');await click(admin,'#btn-class-rates-setup');await admin.waitForSelector('#teacher-policy-editor');};
    const fill=async(selector,value)=>{await admin.$eval(selector,(el,v)=>{el.value=String(v);el.dispatchEvent(new Event('input',{bubbles:true}));},value);};
    const save=async()=>{await click(admin,'button[onclick="saveSalarySettingsFromModal()"]');await admin.waitForFunction(()=>!window.__payrollWritePending);};
    await open();
    assert.match(await admin.$eval('#teacher-policy-editor',e=>e.innerText),/chế độ mới/);
    assert.deepEqual(await read(),original,'opening preview never writes payroll');
    await fill('#teacher-policy-rate',1234);
    await save();
    assert.deepEqual(await read(),original,'typing without applying cannot save a partial policy');
    await click(admin,'#teacher-policy-apply');
    assert.equal(await admin.$eval('.modal-eval-amount[data-index="0"]',e=>e.value),'4,936','only four teaching hours, not two receptionist hours');
    assert.deepEqual(await read(),original,'apply stages locally');
    await save();
    let saved=await read();
    assert.equal(attendance(saved),4936);
    assert.equal(saved.giao_vien.teacherAttendancePolicy.input.rate,'1234');
    assert.equal(saved.giao_vien.teacherAttendanceHistory.length,1);
    assert.deepEqual(saved.tiep_tan,original.tiep_tan);
    assert.equal(saved.giao_vien.advance,original.giao_vien.advance);
    assert.deepEqual(saved.giao_vien.class_rates,original.giao_vien.class_rates);
    assert.equal(saved.published.details_gv.netPay,384936);
    await open();
    assert.equal(await admin.$eval('#teacher-policy-rate',e=>e.value),'1234');
    assert.equal(await admin.$eval('.modal-eval-amount[data-index="0"]',e=>e.value),'4,936');
    await admin.$eval('#teacher-policy-editor',e=>e.scrollIntoView({block:'center'}));
    await admin.screenshot({path:require('node:path').join(__dirname,'../scratch/teacher-attendance-new.png'),fullPage:false});
    await save(); assert.equal(attendance(await read()),4936,'unchanged loaded source survives Firestore key reordering'); await open();
    await click(admin,'#teacher-policy-restore'); await save();
    saved=await read(); assert.equal(attendance(saved),10000); assert.equal(saved.giao_vien.teacherAttendancePolicy.restored,true);
    // An already sent salary is immutable; zero creates a separate revision.
    saved.published.status='received';saved.published.status_gv='received';saved.published.status_tt='received';
    await write(saved);
    await open();await fill('#teacher-policy-rate',0);await click(admin,'#teacher-policy-apply');await save();
    const zero=await read();
    assert.equal(attendance(zero),0);
    assert.deepEqual(zero.published,saved.published,'received snapshot untouched');
    assert.equal(zero.revisionDrafts.gv.payload.details_gv.netPay,380000);
    assert.equal(zero.revisionDrafts.tt,undefined);
    await admin.evaluate(async m=>{const d=window.currentMonthlySalarySettingsAll.revisionDrafts.gv;await DBService.publishPayslipRevision('audit-dual',m,'gv',d.sourceToken,d.version,'Test chuyên cần về 0');},month);
    const sent=await read();assert.equal(sent.published.details_gv.netPay,380000);assert.deepEqual(sent.published.details_tt,saved.published.details_tt);
    await open();await fill('#teacher-policy-rate',9000);await click(admin,'#teacher-policy-apply');
    const concurrent=await read(); concurrent.giao_vien.advance=12345; await write(concurrent);
    await save();assert.deepEqual(await read(),concurrent,'stale save cannot overwrite another admin');
    // Old mode uses the same editor and criterion slots; unrelated bonuses survive.
    await write(original);
    await env.withSecurityRulesDisabled(c=>c.firestore().collection('users').doc(id).update({teachingMode:'old'}));
    await open();
    assert.equal(await admin.$eval('#teacher-policy-apply',e=>e.disabled),true);
    for(const key of ['eligible','fixed','hoursBonus','hoursCondition','meetingEnabled']) await click(admin,`#teacher-policy-editor [data-policy="${key}"]`);
    await admin.select('#teacher-policy-editor [data-policy="meeting"]','present');
    await admin.$eval('#teacher-policy-editor',e=>e.scrollIntoView({block:'center'}));
    await admin.screenshot({path:require('node:path').join(__dirname,'../scratch/teacher-attendance-old.png'),fullPage:false});
    await click(admin,'#teacher-policy-apply');
    assert.equal(await admin.$eval('.modal-eval-amount[data-index="0"]',e=>e.value),'0');
    assert.equal(await admin.$eval('.modal-eval-amount[data-index="9"]',e=>e.value),'30,000');
    await save();
    const old=await read();assert.equal(old.published.details_gv.netPay,410000);assert.equal(old.giao_vien.teacherAttendancePolicy.input.mode,'old');
    await open();
    await admin.$eval('#teacher-policy-editor details',e=>e.open=true);
    await click(admin,'#teacher-policy-editor [data-policy="lateEnabled"]');
    await admin.select('#teacher-policy-editor [data-policy="lateRate"]','1000');
    await fill('#modal-adjust-late',5000);
    await click(admin,'#teacher-policy-apply');
    assert.match(await admin.$eval('#teacher-policy-preview',e=>e.innerText),/Đã có khoản khấu trừ trễ/);
    assert.deepEqual(await read(),old,'existing penalty is preserved and never silently duplicated');
    await open();
    // Source change requires reapplication, never silently saves stale hours.
    await admin.evaluate(()=>{window.unfilteredAllMonthChips.push({isTeaching:true,paidMinutes:60,text:'test'});});
    await save();assert.deepEqual(await read(),old);
    await open();
    await admin.evaluate(()=>{localStorage.setItem('currentRole','senior_assistant');TeacherAttendanceEditor.mount(window.currentLoadedSalarySettings);});
    assert.equal(await admin.$eval('#teacher-policy-editor fieldset',e=>e.disabled),true,'senior manager preview is read-only');
    await admin.evaluate(()=>localStorage.setItem('currentRole','admin'));
    await record('teacher-attendance-policy',{newNet:384936,zeroRevisionNet:380000,oldMeetingNet:410000,conflict:true,restore:true,seniorReadOnly:true});
    await env.withSecurityRulesDisabled(c=>c.firestore().collection('users').doc(id).set(profile));
    await write(original);
    await report(admin,id);
};
